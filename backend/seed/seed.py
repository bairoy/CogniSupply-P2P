def log_event(cur, entity_type, entity_id, event_type, payload, created_at):
    """
    Historical event_log row. redis_published = TRUE on purpose: these events
    predate the live stream, and marking them FALSE would make
    reconcile_unpublished() flood a running dashboard with days of history.
    """
    cur.execute(
        """
        INSERT INTO event_log (entity_type, entity_id, event_type, payload,
                               redis_published, created_at)
        VALUES (%s, %s, %s, %s, TRUE, %s)
        """,
        (entity_type, entity_id, event_type, json.dumps(payload), created_at),
    )


def seed_master(cur):
    # Hash once, not once per user: bcrypt is deliberately slow (~100ms), and
    # seven identical hashes of the same demo password add nothing but delay.
    demo_hash = hash_password(DEMO_PASSWORD)

    for uid, name, role, email in USERS:
        # DO UPDATE, not DO NOTHING, on the credential columns: a database
        # seeded before v5 already has these user rows, so DO NOTHING would
        # leave every demo account permanently unable to log in. Name and role
        # are left alone -- an admin may have re-roled someone since.
        cur.execute(
            """INSERT INTO users (id, name, role, email, password_hash, is_active)
               VALUES (%s,%s,%s,%s,%s,TRUE)
               ON CONFLICT (id) DO UPDATE
                   SET email         = EXCLUDED.email,
                       password_hash = EXCLUDED.password_hash,
                       is_active     = TRUE""",
            (uid, name, role, email, demo_hash if email else None),
        )

    for lid, name, ltype, lat, lon in LOCATIONS:
        cur.execute(
            """INSERT INTO locations (id, name, location_type, latitude, longitude)
               VALUES (%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING""",
            (lid, name, ltype, lat, lon),
        )

    for sid, name, loc, rel, lead, qual, risk, mult in SUPPLIERS:
        cur.execute(
            """INSERT INTO suppliers (id, name, location_id, reliability_score,
                                      avg_lead_time_days, quality_score, risk_score, metadata)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING""",
            (sid, name, loc, rel, lead, qual, risk, json.dumps({"price_multiplier": mult})),
        )

    for mid, name, uom, price, category, supplier in MATERIALS:
        cur.execute(
            """INSERT INTO materials (id, name, uom, default_supplier_id, metadata)
               VALUES (%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING""",
            (mid, name, uom, supplier, json.dumps({"base_price": price, "category": category})),
        )

    for did, loads, pos, active, unload_min in DOCKS:
        cur.execute(
            """INSERT INTO docks (id, compatible_load_types, yard_position, is_active, metadata)
               VALUES (%s,%s,%s,%s,%s) ON CONFLICT (id) DO NOTHING""",
            (did, loads, pos, active, json.dumps({"expected_unload_minutes": unload_min})),
        )

    print(f"  master data: {len(USERS)} users "
          f"(login: any email below / {DEMO_PASSWORD}), {len(LOCATIONS)} locations, "
          f"{len(SUPPLIERS)} suppliers, {len(MATERIALS)} materials, {len(DOCKS)} docks")


