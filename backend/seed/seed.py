# Lifecycle stage for the 40 chains, so the pipeline funnel and yard board have
# realistic spread instead of everything sitting in one column.
COMPLETE_CHAINS = 26   # reach 3-way matching
IN_FLIGHT = {
    "po_only": 4,      # PO created, nothing shipped
    "en_route": 4,     # trailer moving, dock ASSIGNED
    "arrived": 3,      # at the gate, dock ASSIGNED
    "docked": 3,       # at the door, dock CONFIRMED, unloading
}

# The mismatch mix, sized against the chains that ACTUALLY REACH MATCHING --
# a mismatch is only observable on a completed pair, so the 26 complete chains
# are the denominator, not all 40. README §7 asks for 20-30%: this is
# 6 chain-level exceptions + 1 duplicate = 7 of 27 match results = 26%.
#
# `near_miss_qty` is the important one: a 1.5% quantity variance that SHOULD
# approve, proving the tolerance boundary works in both directions rather than
# only that mismatches fail.
#
# `duplicate_invoice` is a clean chain that later receives a SECOND invoice
# against the now-settled PO, so its own match approves and the duplicate is
# what raises the exception -- which is exactly how it happens in reality.
COMPLETE_SCENARIOS = (
    ["clean"] * 18
    + ["near_miss_qty"] * 1
    + ["qty_mismatch"] * 3
    + ["price_mismatch"] * 2
    + ["missing_po"] * 1
    + ["duplicate_invoice"] * 1
)
assert len(COMPLETE_SCENARIOS) == COMPLETE_CHAINS


def build_plan():
    """(scenario, stage) for all 40 chains, interleaved so created_at mixes."""
    paired = [(s, "complete") for s in COMPLETE_SCENARIOS]
    for stage, count in IN_FLIGHT.items():
        # In-flight chains have not been invoiced yet, so they carry no
        # mismatch scenario -- there is nothing to mismatch against.
        paired += [("clean", stage)] * count
    assert len(paired) == 40
    random.shuffle(paired)
    return paired


def build_occupancy(cur):
    cur.execute(
        "SELECT dock_id, trailer_id FROM dock_assignments WHERE status IN ('ASSIGNED','CONFIRMED')"
    )
    return {row[0]: row[1] for row in cur.fetchall()}


def fetch_docks(cur):
    cur.execute("SELECT id, compatible_load_types, yard_position, is_active FROM docks")
    return [
        {"id": r[0], "compatible_load_types": r[1], "yard_position": r[2], "is_active": r[3]}
        for r in cur.fetchall()
    ]


def seed_traffic(cur):
    docks = fetch_docks(cur)
    ground_truth = []

    for scenario, stage in build_plan():
        age_days = random.uniform(0.2, 7.0)
        t0 = NOW - timedelta(days=age_days)

        material = random.choice(MATERIALS)
        mat_id, mat_name, uom, base_price, category, default_supplier = material
        supplier = next(s for s in SUPPLIERS if s[0] == default_supplier)
        sup_id, sup_name, sup_loc, rel, lead, qual, risk, mult = supplier

        qty = Decimal(random.choice([50, 100, 120, 200, 250, 400, 500, 750, 1000]))
        unit_price = (Decimal(str(base_price)) * Decimal(str(mult))).quantize(Decimal("0.01"))

        # --- requisition ---
        req_id = next_id(cur, "REQ")
        requester = random.choice([u[0] for u in USERS if u[2] == "procurement"])
        raw_text = f"We need {qty} {uom} of {mat_name} delivered to the Chicago plant"
        parsed = {
            "material_id": mat_id, "material_name": mat_name, "qty": float(qty),
            "uom": uom, "delivery_location_id": "LOC-001",
            "confidence": round(random.uniform(0.88, 0.99), 3), "ambiguities": [],
            "source": "seed",
        }
        cur.execute(
            """INSERT INTO requisitions (id, requested_by, raw_text, parsed, status, created_at)
               VALUES (%s,%s,%s,%s,%s,%s)""",
            (req_id, requester, raw_text, json.dumps(parsed), "CONVERTED", t0),
        )
        log_event(cur, "requisition", req_id, "REQUISITION_CREATED",
                  {"summary": f"{req_id} raised for {qty} {uom} {mat_name}",
                   "material_id": mat_id, "qty": float(qty)}, t0)

        # --- supplier recommendations (all candidates, not just the winner) ---
        candidates = [s for s in SUPPLIERS if s[0] == sup_id]
        others = [s for s in SUPPLIERS if s[0] != sup_id]
        candidates += random.sample(others, 2)
        scored = []
        for cand in candidates:
            c_id, c_name, _, c_rel, c_lead, c_qual, c_risk, c_mult = cand
            price_score = round(1.0 - min(c_mult - 0.8, 0.4) / 0.4, 3)
            lead_score = round(1.0 - min(c_lead, 10) / 10, 3)
            overall = round(
                0.30 * price_score + 0.25 * c_qual + 0.20 * lead_score
                + 0.15 * c_rel + 0.10 * (1 - c_risk), 3
            )
            scored.append((cand, price_score, lead_score, overall))
        scored.sort(key=lambda x: -x[3])

        for rank, (cand, price_score, lead_score, overall) in enumerate(scored, start=1):
            c_id, c_name, _, c_rel, c_lead, c_qual, c_risk, c_mult = cand
            sr_id = next_id(cur, "SR")
            is_winner = c_id == sup_id
            reasoning = (
                f"{c_name} scores {overall:.2f} overall: quality {c_qual:.2f}, "
                f"reliability {c_rel:.2f}, {c_lead}-day lead time, "
                f"unit price {Decimal(str(base_price)) * Decimal(str(c_mult)):.2f}."
                + (" Selected as best overall fit." if is_winner
                   else " Not selected -- lower combined score.")
            )
            cur.execute(
                """INSERT INTO supplier_recommendations
                   (id, requisition_id, supplier_id, price_score, quality_score,
                    lead_time_score, reliability_score, risk_score, overall_score,
                    rank, recommended, quoted_unit_price, quoted_lead_time_days,
                    reasoning, created_at)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
                (sr_id, req_id, c_id, price_score, c_qual, lead_score, c_rel, c_risk,
                 overall, rank, is_winner,
                 (Decimal(str(base_price)) * Decimal(str(c_mult))).quantize(Decimal("0.01")),
                 c_lead, reasoning, t0),
            )
        log_event(cur, "requisition", req_id, "SUPPLIER_RECOMMENDED",
                  {"summary": f"{len(scored)} suppliers scored for {req_id}; "
                              f"{sup_name} recommended",
                   "recommended_supplier_id": sup_id}, t0)

        # --- purchase order ---
        po_id = next_id(cur, "PO")
        expected_delivery = t0 + timedelta(days=lead)
        po_status = "CREATED"
        cur.execute(
            """INSERT INTO purchase_orders
               (id, requisition_id, supplier_id, material_id, qty, unit_price,
                delivery_location_id, expected_delivery, terms, status, created_at, updated_at)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
            (po_id, req_id, sup_id, mat_id, qty, unit_price, "LOC-001", expected_delivery,
             json.dumps({"payment_terms": "NET30", "currency": "USD", "incoterm": "DAP"}),
             po_status, t0, t0),
        )
        log_event(cur, "purchase_order", po_id, "PO_CREATED",
                  {"summary": f"{po_id} raised with {sup_name} for {qty} {uom} {mat_name}",
                   "supplier_id": sup_id, "qty": float(qty),
                   "unit_price": float(unit_price)}, t0)

        record = {
            "po_id": po_id, "requisition_id": req_id, "scenario": scenario,
            "stage": stage, "supplier_id": sup_id, "material_id": mat_id,
            "po_qty": float(qty), "po_unit_price": float(unit_price),
        }

        if stage == "po_only":
            ground_truth.append({**record, "expected_match_status": None,
                                 "expected_exception_type": None})
            continue

        # --- shipment ---
        t_ship = t0 + timedelta(hours=random.uniform(4, 20))
        shp_id = next_id(cur, "SHP")
        carrier = random.choice(CARRIERS)
        tracking = f"TRK{random.randint(100000, 999999)}"
        eta = t_ship + timedelta(hours=random.uniform(6, 30))
        shipment_status = {"complete": "UNLOADED", "en_route": "EN_ROUTE",
                           "arrived": "ARRIVED", "docked": "ARRIVED"}[stage]
        cur.execute(
            """INSERT INTO shipments (id, po_id, tracking_number, carrier,
                   origin_location_id, destination_location_id, expected_arrival,
                   status, created_at)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
            (shp_id, po_id, tracking, carrier, sup_loc, "LOC-001", eta, shipment_status, t_ship),
        )
        cur.execute("UPDATE purchase_orders SET status='SHIPPED', updated_at=%s WHERE id=%s",
                    (t_ship, po_id))
        po_status = "SHIPPED"
        log_event(cur, "shipment", shp_id, "SHIPMENT_CREATED",
                  {"summary": f"{shp_id} despatched by {carrier} for {po_id}",
                   "po_id": po_id, "carrier": carrier, "tracking_number": tracking}, t_ship)

        # --- trailer ---
        trl_id = next_id(cur, "TRL")
        load_type = random.choice(LOAD_TYPES[:3])  # tanker door is the inactive one
        priority = random.choices(["low", "normal", "high", "critical"],
                                  weights=[1, 5, 3, 1])[0]
        trailer_status = {"complete": "UNLOADED", "en_route": "EN_ROUTE",
                          "arrived": "ARRIVED", "docked": "DOCKED"}[stage]
        cur.execute(
            """INSERT INTO trailers (id, shipment_id, load_type, priority, eta, status,
                                     created_at, updated_at)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s)""",
            (trl_id, shp_id, load_type, priority, eta, trailer_status, t_ship, t_ship),
        )
        log_event(cur, "trailer", trl_id, "TRAILER_DEPARTED",
                  {"summary": f"{trl_id} departed {sup_name} ({load_type}, {priority} priority)",
                   "shipment_id": shp_id, "load_type": load_type, "priority": priority}, t_ship)

        # --- GPS breadcrumbs ---
        origin = next(loc for loc in LOCATIONS if loc[0] == sup_loc)
        dest = next(loc for loc in LOCATIONS if loc[0] == "LOC-001")
        ticks = {"complete": 8, "en_route": random.randint(3, 6),
                 "arrived": 9, "docked": 9}[stage]
        progress_cap = {"complete": 1.0, "en_route": random.uniform(0.35, 0.8),
                        "arrived": 1.0, "docked": 1.0}[stage]
        for i in range(ticks):
            frac = (i + 1) / ticks * progress_cap
            lat = origin[3] + (dest[3] - origin[3]) * frac + random.uniform(-0.02, 0.02)
            lon = origin[4] + (dest[4] - origin[4]) * frac + random.uniform(-0.02, 0.02)
            recorded = t_ship + timedelta(hours=frac * 12)
            cur.execute(
                """INSERT INTO tracking_events (trailer_id, latitude, longitude, speed,
                                                eta_estimate, recorded_at)
                   VALUES (%s,%s,%s,%s,%s,%s)""",
                (trl_id, round(lat, 5), round(lon, 5), round(random.uniform(45, 68), 1),
                 eta, recorded),
            )
        cur.execute("UPDATE trailers SET eta=%s WHERE id=%s", (eta, trl_id))

        # --- dock assignment, via the real engine ---
        occupancy = build_occupancy(cur)
        decision = decide(docks=docks, trailer_id=trl_id, trailer_load_type=load_type,
                          priority=priority, occupancy=occupancy)
        t_assign = t_ship + timedelta(minutes=random.uniform(20, 90))

        if decision.winner is None:
            alt_id = next_id(cur, "ALT")
            cur.execute(
                """INSERT INTO alerts (id, entity_type, entity_id, alert_type, message,
                                       severity, acknowledged, created_at)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s)""",
                (alt_id, "trailer", trl_id, "DOCK_CONFLICT", decision.reason,
                 "warning", False, t_assign),
            )
            log_event(cur, "alert", alt_id, "ALERT_CREATED",
                      {"summary": decision.reason, "alert_type": "DOCK_CONFLICT"}, t_assign)
            da_id = None
        else:
            da_id = next_id(cur, "DA")
            da_status = {"complete": "COMPLETED", "en_route": "ASSIGNED",
                         "arrived": "ASSIGNED", "docked": "CONFIRMED"}[stage]
            docked_at = None
            if stage == "docked":
                # Recent docked_at so the board shows a live unloading percentage.
                docked_at = NOW - timedelta(minutes=random.uniform(5, 35))
            elif stage == "complete":
                docked_at = t_assign + timedelta(minutes=random.uniform(30, 120))
            cur.execute(
                """INSERT INTO dock_assignments (id, trailer_id, dock_id, assigned_at,
                                                 status, reason, score_breakdown, docked_at)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s)""",
                (da_id, trl_id, decision.winner, t_assign, da_status, decision.reason,
                 json.dumps(decision.breakdown), docked_at),
            )
            log_event(cur, "dock_assignment", da_id, "DOCK_ASSIGNED",
                      {"summary": decision.reason, "trailer_id": trl_id,
                       "dock_id": decision.winner,
                       "final_score": decision.breakdown.get("final_score")}, t_assign)

        if stage in ("arrived", "docked", "complete"):
            t_arrive = t_assign + timedelta(minutes=random.uniform(30, 180))
            log_event(cur, "trailer", trl_id, "TRAILER_ARRIVED",
                      {"summary": f"{trl_id} arrived at the gate", "shipment_id": shp_id},
                      t_arrive)
        if stage in ("docked", "complete"):
            log_event(cur, "trailer", trl_id, "TRAILER_DOCKED",
                      {"summary": f"{trl_id} docked at {decision.winner}",
                       "dock_id": decision.winner}, docked_at or t_assign)

        if stage != "complete":
            ground_truth.append({**record, "trailer_id": trl_id, "shipment_id": shp_id,
                                 "expected_match_status": None,
                                 "expected_exception_type": None})
            continue

        # --- goods receipt (E2-owned) ---
        t_receipt = t_assign + timedelta(hours=random.uniform(2, 8))
        qty_received = qty
        gr_id = next_id(cur, "GR")
        cur.execute(
            """INSERT INTO goods_receipts (id, trailer_id, shipment_id, po_id,
                                           qty_received, received_at, verified_by)
               VALUES (%s,%s,%s,%s,%s,%s,%s)""",
            (gr_id, trl_id, shp_id, po_id, qty_received, t_receipt, "simulated_cv"),
        )
        cur.execute("UPDATE shipments SET status='UNLOADED' WHERE id=%s", (shp_id,))
        cur.execute("UPDATE purchase_orders SET status='RECEIVED', updated_at=%s WHERE id=%s",
                    (t_receipt, po_id))
        po_status = "RECEIVED"
        log_event(cur, "goods_receipt", gr_id, "GOODS_RECEIVED",
                  {"summary": f"{gr_id}: {qty_received} {uom} received against {po_id}",
                   "po_id": po_id, "qty_received": float(qty_received),
                   "trailer_id": trl_id}, t_receipt)

        # --- invoice, shaped by the scenario ---
        t_invoice = t_receipt + timedelta(hours=random.uniform(1, 30))
        inv_qty, inv_price, inv_po = qty_received, unit_price, po_id

        if scenario == "qty_mismatch":
            inv_qty = (qty_received * Decimal(random.choice(["1.10", "1.08", "0.90", "1.15"]))
                       ).quantize(Decimal("0.01"))
        elif scenario == "near_miss_qty":
            inv_qty = (qty_received * Decimal("1.015")).quantize(Decimal("0.01"))
        elif scenario == "price_mismatch":
            inv_price = (unit_price * Decimal(random.choice(["1.06", "1.09", "0.92", "1.12"]))
                         ).quantize(Decimal("0.01"))
        elif scenario == "missing_po":
            inv_po = None

        tax = (inv_qty * inv_price * Decimal("0.08")).quantize(Decimal("0.01"))
        total = (inv_qty * inv_price + tax).quantize(Decimal("0.01"))
        inv_id = next_id(cur, "INV")
        confidence = round(random.uniform(0.91, 0.995), 3)
        cur.execute(
            """INSERT INTO invoices (id, po_id, qty_invoiced, unit_price_invoiced, tax,
                                     total, ocr_confidence, ocr_raw, received_at)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
            (inv_id, inv_po, inv_qty, inv_price, tax, total, confidence,
             json.dumps({
                 "vendor": sup_name, "po_reference": inv_po,
                 "field_confidence": {
                     "supplier_name": round(random.uniform(0.95, 0.999), 3),
                     "po_reference": 0.0 if inv_po is None else round(random.uniform(0.9, 0.99), 3),
                     "qty_invoiced": round(random.uniform(0.92, 0.99), 3),
                     "unit_price_invoiced": round(random.uniform(0.92, 0.99), 3),
                     "total": round(random.uniform(0.97, 0.999), 3),
                 },
                 "engine": "seed",
             }), t_invoice),
        )
        log_event(cur, "invoice", inv_id, "INVOICE_RECEIVED",
                  {"summary": f"{inv_id} received from {sup_name} "
                              f"({inv_qty} @ {inv_price})",
                   "po_id": inv_po, "total": float(total)}, t_invoice)
        log_event(cur, "invoice", inv_id, "OCR_COMPLETED",
                  {"summary": f"OCR extracted {inv_id} at {confidence:.1%} confidence",
                   "ocr_confidence": confidence}, t_invoice)

        # --- 3-way match, via the real locked policy ---
        decision_m = evaluate(
            po_id=inv_po, po_status=po_status, po_qty=qty, po_unit_price=unit_price,
            qty_received=qty_received, qty_invoiced=inv_qty,
            unit_price_invoiced=inv_price,
        )
        t_match = t_invoice + timedelta(minutes=random.uniform(1, 10))
        mr_id = next_id(cur, "MR")
        cur.execute(
            """INSERT INTO match_results (id, po_id, goods_receipt_id, invoice_id,
                                          status, reason, created_at)
               VALUES (%s,%s,%s,%s,%s,%s,%s)""",
            (mr_id, inv_po, gr_id, inv_id, decision_m.status, decision_m.reason, t_match),
        )
        log_event(cur, "match_result", mr_id, "MATCH_COMPLETED",
                  {"summary": f"{mr_id}: {decision_m.status} -- {decision_m.reason}",
                   "po_id": inv_po, "invoice_id": inv_id,
                   "status": decision_m.status}, t_match)

        if decision_m.approved:
            pay_id = next_id(cur, "PAY")
            paid = random.random() < 0.6
            cur.execute(
                """INSERT INTO payments (id, invoice_id, amount, status, approved_by,
                                         approved_at, paid_at, created_at)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s)""",
                (pay_id, inv_id, total, "PAID" if paid else "APPROVED", "USR-005",
                 t_match, t_match + timedelta(days=1) if paid else None, t_match),
            )
            cur.execute(
                "UPDATE purchase_orders SET status=%s, updated_at=%s WHERE id=%s",
                ("CLOSED" if paid else "MATCHED", t_match, po_id),
            )
            log_event(cur, "payment", pay_id, "PAYMENT_APPROVED",
                      {"summary": f"{pay_id} approved for {total} against {inv_id}",
                       "invoice_id": inv_id, "amount": float(total)}, t_match)
            if paid:
                log_event(cur, "payment", pay_id, "PAYMENT_PAID",
                          {"summary": f"{pay_id} paid ({total})", "amount": float(total)},
                          t_match + timedelta(days=1))
        else:
            exc_id = next_id(cur, "EXC")
            assignee = random.choice([u[0] for u in USERS if u[2] in ("procurement", "finance")])
            cur.execute(
                """INSERT INTO exceptions (id, match_result_id, exception_type, status,
                                           assigned_to, severity, impact_amount, created_at)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s)""",
                (exc_id, mr_id, decision_m.exception_type, "OPEN", assignee,
                 decision_m.severity or SEVERITY_BY_TYPE.get(decision_m.exception_type, "medium"),
                 decision_m.impact_amount, t_match),
            )
            log_event(cur, "exception", exc_id, "EXCEPTION_CREATED",
                      {"summary": f"{exc_id}: {decision_m.exception_type} on "
                                  f"{inv_po or 'unmatched invoice'} -- {decision_m.reason}",
                       "exception_type": decision_m.exception_type,
                       "severity": decision_m.severity,
                       "impact_amount": float(decision_m.impact_amount or 0)}, t_match)

        # --- duplicate invoice: a SECOND invoice against a now-settled PO ---
        if scenario == "duplicate_invoice":
            cur.execute("SELECT status FROM purchase_orders WHERE id=%s", (po_id,))
            settled_status = cur.fetchone()[0]
            t_dup = t_match + timedelta(hours=random.uniform(2, 24))
            dup_id = next_id(cur, "INV")
            cur.execute(
                """INSERT INTO invoices (id, po_id, qty_invoiced, unit_price_invoiced, tax,
                                         total, ocr_confidence, ocr_raw, received_at)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
                (dup_id, po_id, inv_qty, inv_price, tax, total, confidence,
                 json.dumps({"vendor": sup_name, "po_reference": po_id, "engine": "seed",
                             "note": "resubmission"}), t_dup),
            )
            log_event(cur, "invoice", dup_id, "INVOICE_RECEIVED",
                      {"summary": f"{dup_id} received from {sup_name} (resubmission)",
                       "po_id": po_id, "total": float(total)}, t_dup)
            dup_decision = evaluate(
                po_id=po_id, po_status=settled_status, po_qty=qty, po_unit_price=unit_price,
                qty_received=qty_received, qty_invoiced=inv_qty,
                unit_price_invoiced=inv_price,
            )
            dup_mr = next_id(cur, "MR")
            cur.execute(
                """INSERT INTO match_results (id, po_id, goods_receipt_id, invoice_id,
                                              status, reason, created_at)
                   VALUES (%s,%s,%s,%s,%s,%s,%s)""",
                (dup_mr, po_id, gr_id, dup_id, dup_decision.status, dup_decision.reason, t_dup),
            )
            dup_exc = next_id(cur, "EXC")
            cur.execute(
                """INSERT INTO exceptions (id, match_result_id, exception_type, status,
                                           assigned_to, severity, impact_amount, created_at)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s)""",
                (dup_exc, dup_mr, dup_decision.exception_type, "OPEN", "USR-005",
                 dup_decision.severity, total, t_dup),
            )
            log_event(cur, "exception", dup_exc, "EXCEPTION_CREATED",
                      {"summary": f"{dup_exc}: DUPLICATE_INVOICE on {po_id} -- "
                                  f"{dup_decision.reason}",
                       "exception_type": dup_decision.exception_type,
                       "severity": dup_decision.severity}, t_dup)
            record["duplicate_invoice_id"] = dup_id

        ground_truth.append({
            **record,
            "trailer_id": trl_id, "shipment_id": shp_id, "goods_receipt_id": gr_id,
            "invoice_id": inv_id, "match_result_id": mr_id,
            "qty_received": float(qty_received), "qty_invoiced": float(inv_qty),
            "unit_price_invoiced": float(inv_price),
            "expected_match_status": decision_m.status,
            "expected_exception_type": decision_m.exception_type,
        })

    return ground_truth


def reset(cur):
    """Truncate every table and restart the ID sequences."""
    cur.execute("""
        TRUNCATE processed_events, audit_logs, event_log, alerts, payments, exceptions,
                 match_results, invoices, goods_receipts, dock_assignments, tracking_events,
                 trailers, shipments, purchase_orders, supplier_recommendations,
                 requisitions, docks, materials, suppliers, locations, users
        RESTART IDENTITY CASCADE
    """)
    for seq in ("requisition_id_seq", "supplier_recommendation_id_seq", "purchase_order_id_seq",
                "shipment_id_seq", "trailer_id_seq", "dock_assignment_id_seq",
                "goods_receipt_id_seq", "invoice_id_seq", "match_result_id_seq",
                "exception_id_seq", "payment_id_seq", "alert_id_seq"):
        cur.execute(f"ALTER SEQUENCE {seq} RESTART WITH 1001")


def main():
    ap = argparse.ArgumentParser(description="Seed the Inbound-to-Pay database.")
    ap.add_argument("--master-only", action="store_true", help="reference data only, no traffic")
    ap.add_argument("--reset", action="store_true", help="truncate everything first")
    args = ap.parse_args()

    with get_conn() as conn:
        with conn.cursor() as cur:
            if args.reset:
                print("• resetting all tables")
                reset(cur)

            print("• seeding master data")
            seed_master(cur)

            ground_truth = []
            if not args.master_only:
                print("• seeding 40 PO chains")
                ground_truth = seed_traffic(cur)

        conn.commit()

    if ground_truth:
        GROUND_TRUTH_PATH.write_text(json.dumps({
            "seed": SEED,
            "generated_at": NOW.isoformat(),
            "chains": ground_truth,
        }, indent=2))
        matched = [g for g in ground_truth if g["expected_match_status"]]
        exceptions = [g for g in matched if g["expected_match_status"] == "EXCEPTION"]
        print(f"  {len(ground_truth)} chains ({len(matched)} reached matching, "
              f"{len(exceptions)} expected exceptions "
              f"= {len(exceptions)/max(len(matched),1):.0%} of matched)")
        print(f"  ground truth -> {GROUND_TRUTH_PATH}")

    print("done.")


if __name__ == "__main__":
    main()
